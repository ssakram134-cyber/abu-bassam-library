'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const file=fs.readFileSync(path.join(__dirname,'..','web/extended-barcode-runtime.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'..','web/index.html'),'utf8');
new vm.Script(file);
const win={addEventListener:()=>{}},doc={};
new Function('window','document',file)(win,doc);
const api=win.AbuBassamExtendedBarcode;
assert.equal(api.normalize('EAN13','400638133393'),'4006381333931');
assert.equal(api.normalize('EAN13','4006381333931'),'4006381333931');
assert.throws(()=>api.normalize('EAN13','4006381333932'),/INVALID_CHECK_DIGIT/);
assert.equal(api.normalize('UPCA','03600029145'),'036000291452');
assert.equal(api.normalize('UPCA','036000291452'),'036000291452');
assert.equal(api.normalize('ITF14','1234567890123').length,14);
assert.throws(()=>api.normalize('UPCA','123'),/BARCODE_LENGTH_12/);
assert.throws(()=>api.normalize('EAN13','12x456789012'),/BARCODE_DIGITS_REQUIRED/);
assert.throws(()=>api.normalize('WRONG','1234'),/BARCODE_UNKNOWN_TYPE/);
assert.equal(api.encode('EAN13','4006381333931').bits.length,95);
assert.equal(api.encode('UPCA','036000291452').bits.length,95);
assert.equal(api.encode('ITF14','1234567890123').bits.startsWith('1010'),true);
assert.equal(api.encode('ITF14','1234567890123').bits.endsWith('1101'),true);
assert.match(api.svg('EAN13','400638133393'),/^<svg/);
assert.match(api.svg('ITF14','1234567890123'),/aria-label="ITF14/);
assert.match(html,/src="extended-barcode-runtime\.js"/);
assert.match(file,/cardsBarcode/);
assert.match(file,/role\('owner'\)|role\?\.\(\)===.owner./);
console.log('Stage85 barcode symbologies pass: EAN-13, UPC-A, ITF-14, GTIN mod-10 validation, 95 modules, valid SVG and cards permission gate.');
