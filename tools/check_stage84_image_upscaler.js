'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'web/image-upscale-runtime.js'),'utf8');
const html=fs.readFileSync(path.join(root,'web/image-compressor.html'),'utf8');
new vm.Script(source);
const win={addEventListener:()=>{}},doc={readyState:'loading',addEventListener:()=>{}};
new Function('window','document','navigator','URL',source)(win,doc,{deviceMemory:4},{});
const up=win.AbuBassamImageUpscale;
assert.deepEqual(up.PRESETS,{QCIF:[176,144],CIF:[352,288],VGA:[640,480],SVGA:[800,600],HD:[1280,720],FHD:[1920,1080],QHD:[2560,1440],UHD4K:[3840,2160],K5:[5120,2880],UHD8K:[7680,4320]});
const landscape=up.geometry(640,480,'FHD');
assert.equal(landscape.width,1920);assert.equal(landscape.height,1080);
assert.equal(landscape.drawWidth,1440);assert.equal(landscape.drawHeight,1080);
assert.equal(landscape.x,240);assert.equal(landscape.y,0);
const portrait=up.geometry(480,640,'FHD');
assert.equal(portrait.width,1080);assert.equal(portrait.height,1920);
const crop=up.geometry(640,480,'FHD','cover');
assert.equal(crop.drawWidth,1920);assert.equal(crop.drawHeight,1440);assert.ok(crop.y<0);
assert.throws(()=>up.geometry(0,100,'HD'),/UPSCALE_INVALID_SOURCE/);
assert.throws(()=>up.geometry(100,100,'INVALID'),/UPSCALE_INVALID_PRESET/);
assert.equal(up.safeSize(7680,4320,18000000),false);
assert.equal(up.safeSize(7680,4320,36000000),true);
assert.equal(up.maxPixels(4),18000000);
assert.equal(up.maxPixels(8),36000000);
assert.match(source,/imageSmoothingQuality='high'/);
assert.match(source,/UPSCALE_MEMORY_LIMIT/);
assert.match(source,/imageSmoothingEnabled=true/);
assert.match(source,/\.commit\(/.source==='X'?/notpossible/:/handler\(\{blob/);
assert.match(html,/id="upscaleOpenBtn"/);
assert.match(html,/upscaleScript.src='image-upscale-runtime.js'/);
assert.match(html,/kind==='upscaled'/);
assert.match(html,/quality:upscaled\?'تكبير أبعاد/);
assert.match(html,/restoreOpenBtn/);
assert.equal([...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].length,1);
console.log('Stage84 image upscaler: 10 presets, aspect/portrait/crop, offline high-quality resize, 8K memory guard, original-safe compressor integration PASS.');
