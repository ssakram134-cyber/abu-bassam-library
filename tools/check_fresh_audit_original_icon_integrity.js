'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),source=fs.readFileSync(path.join(root,'tools/validate_imported_source.js'),'utf8');
const a=source.indexOf('function validateOriginalIcon(expo){'),b=source.indexOf('\nvalidateOriginalIcon(app);',a);
assert.ok(a>=0&&b>a);
const fragment=source.slice(a,b);
assert.match(fragment,/expo\.icon!=='\.\/assets\/icon\.png'/);
assert.match(fragment,/adaptiveIcon\?\.foregroundImage!=='\.\/assets\/icon\.png'/);
const match=fragment.match(/gitSha!=='([0-9a-f]{40})'/);
assert.ok(match,'Must compare imported icon with trusted Git blob fingerprint');
assert.equal(match[1],'acf4999f8c52bd921b12f1e9fdf809cc4cca7d6f');
const approved=fs.readFileSync(path.join(root,'assets/icon.png'));
const currentHash=crypto.createHash('sha1').update(Buffer.from('blob '+approved.length+'\0')).update(approved).digest('hex');
assert.equal(currentHash,match[1],'Current source icon must be the protected original');
const mockImage=Buffer.from(approved),mockConfig={icon:'./assets/icon.png',android:{adaptiveIcon:{foregroundImage:'./assets/icon.png'}}};
let blob=mockImage;
const fakeFs={existsSync:()=>true,readFileSync:()=>blob};
const fail=msg=>{throw Error(msg)};
const verify=new Function('fs','path','crypto','Buffer','root','fail',fragment+';return validateOriginalIcon')(fakeFs,path,crypto,Buffer,root,fail);
assert.doesNotThrow(()=>verify(mockConfig));
assert.throws(()=>verify({...mockConfig,icon:'./assets/other.png'}),/icon paths/);
blob=Buffer.from(mockImage);blob[blob.length-10]^=1;
assert.throws(()=>verify(mockConfig),/was replaced/);
blob=Buffer.alloc(40);
assert.throws(()=>verify(mockConfig),/not a PNG/);
console.log('Fresh audit source ZIP: original app and adaptive icon paths, PNG bytes and trusted Git blob identity verified.');
