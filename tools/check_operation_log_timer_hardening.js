'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'..','web','operation-log-corrections-runtime.js'),'utf8');
new vm.Script(source,{filename:'operation-log-corrections-runtime.js'});
const boot=source.slice(source.indexOf('function boot(){'),source.indexOf('window.AbuBassamOperationLogV2='));
assert.ok(boot.startsWith('function boot(){'),'Expected operation log boot function');
assert.doesNotMatch(boot,/setInterval\(patch\s*,\s*2500\s*\)/,'Unconditional 2.5s patch polling should be removed');
assert.doesNotMatch(boot,/\.observe\(document\.documentElement/,'Root-wide observer should not process every DOM mutation');
assert.match(boot,/observer\.observe\(toolbar,\{childList:true,subtree:true\}\)/,'Observe only toolbar changes');
assert.match(boot,/if\(patch\(\)\|\|attempts>=80\)clearInterval\(fast\)/,'Stop fast polling as soon as patch works');
assert.match(boot,/document\.visibilityState!=='hidden'/,'Skip periodic scans while hidden');
assert.match(boot,/abu-runtime-loaded/,'Recheck after runtime module replacement');
assert.match(boot,/visibilitychange/,'Reconnect when app returns to foreground');
assert.match(boot,/abu-bassam-auth-changed/,'Preserve auth-change cleanup');
assert.match(boot,/window\.addEventListener\('online'/,'Preserve online synchronization');
console.log('Operation log timer/observer regression passed');
